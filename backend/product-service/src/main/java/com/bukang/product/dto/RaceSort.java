package com.bukang.product.dto;

/**
 * 공개 대회 목록의 정렬 (프론트 대회 찾기 화면의 정렬 4가지 + 정확도순)
 */
public enum RaceSort {
	// 정확도순: 검색어와 잘 맞는 대회부터 (대회명 3배, 장소 2배 가중치). 점수가 같으면 마감 임박순
	RELEVANCE,
	// 마감 임박순: 접수 마감 일시가 이른 대회부터
	DEADLINE,
	// 대회일 빠른순
	RACE_DATE,
	// 최신 등록순: 대회 등록 일시가 늦은 대회부터
	LATEST,
	// 가격 낮은순: 조건에 맞은 종목 중 가장 싼 종목의 참가비 기준 (조건이 없으면 대회에서 가장 싼 종목)
	PRICE
}
